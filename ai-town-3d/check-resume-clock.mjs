import { build } from 'esbuild';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const compiled=await build({entryPoints:['source-backend/convex/aiTown/resumeClock.ts'],bundle:true,write:false,format:'esm'});
const {rebasePausedWorld}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const source=JSON.parse(fs.readFileSync('source-world/world-snapshot.json','utf8')).tables;
const world=structuredClone(source.worlds[0]),society=structuredClone(source.societyWorlds[0]);
const before=source.engines[0].currentTime,gap=5*86400000,now=before+gap;
world.players[0].pathfinding={state:{kind:'moving',path:[[1,2,0,1,before]]},started:before};
const event={_id:'event',endsAt:before+1000};
const ctx={db:{get:async()=>world,patch:async(id,patch)=>Object.assign(id===world._id?world:id===society._id?society:event,patch),query:table=>({withIndex:()=>({unique:async()=>society,collect:async()=>[event]})})}};
await rebasePausedWorld(ctx,world._id,before,now);
assert.equal(society.simulatedDay,40);
assert.equal(society.simStartedAt-source.societyWorlds[0].simStartedAt,gap);
assert.equal(Math.floor((now-society.simStartedAt)/1800000),Math.floor((before-source.societyWorlds[0].simStartedAt)/1800000));
assert.equal(world.players[0].pathfinding.state.path[0][4],now);
assert.equal(world.conversations[0].created-source.worlds[0].conversations[0].created,gap);
assert.deepEqual(world.players.map(p=>p.position),source.worlds[0].players.map(p=>p.position));
assert.equal(event.endsAt,now+1000);
assert(world.agents.every(a=>!a.inProgressOperation));
console.log('PASS: five-day pause preserves day, day phase, positions, live conversation/path timers; no history rewritten');
